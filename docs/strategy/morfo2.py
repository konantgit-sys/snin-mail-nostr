def score(c):
    s = [0]*5
    for k, v in c.items():
        w = W.get((k, v))
        if not w: return None
        for i in range(5): s[i] += w[i]
    return sum(s), s


import itertools
best_by_client, best_by_unit, best_by_payer, all_top = {}, {}, {}, []
for combo in itertools.product(*[OSI[k] for k in K]):
    c = dict(zip(K, combo))
    if not ok(c): continue
    r = score(c)
    if not r: continue
    rec = {"score": r[0], "combo": c}
    all_top.append(rec)
    for store, key in ((best_by_client, "тип клиента"), (best_by_unit, "за что платит"), (best_by_payer, "кто платит")):

        cur = store.get(c[key])
        if not cur or r[0] > cur["score"]: store[c[key]] = rec
all_top.sort(key=lambda x: -x["score"])
